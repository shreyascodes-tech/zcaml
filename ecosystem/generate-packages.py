# opam's version comparison, from OpamVersionCompare.compare.
def _is_digit(c):
    return '0' <= c <= '9'

def _is_alpha(c):
    return ('a' <= c <= 'z') or ('A' <= c <= 'Z')

def _skip_zeros(s, i, end):
    while i < end and s[i] == '0':
        i += 1
    return i

def _skip_while_from(i, pred, s, end):
    while i < end and pred(s[i]):
        i += 1
    return i

def _compare_chars(c1, c2):
    if c1 == '~':
        return 0 if c2 == '~' else -1
    if _is_alpha(c1):
        if c2 == '~':
            return 1
        if _is_alpha(c2):
            return (c1 > c2) - (c1 < c2)
        return -1
    if c2 == '~' or _is_alpha(c2):
        return 1
    return (c1 > c2) - (c1 < c2)

def _loop_lexical(xl, yl, x, y, xi, yi):
    while True:
        if xi == xl and yi == yl:
            return 0
        if xi == xl:
            ys = _skip_zeros(y, yi, yl)
            if ys == yl:
                return 0
            return 1 if y[ys] == '~' else -1
        if yi == yl:
            xs = _skip_zeros(x, xi, xl)
            if xs == xl:
                return 0
            return -1 if x[xs] == '~' else 1
        xd, yd = _is_digit(x[xi]), _is_digit(y[yi])
        if xd and yd:
            return _compare_numerical(xl, yl, x, y, _skip_zeros(x, xi, xl), _skip_zeros(y, yi, yl))
        if xd and not yd:
            return 1 if y[yi] == '~' else -1
        if not xd and yd:
            return -1 if x[xi] == '~' else 1
        c = _compare_chars(x[xi], y[yi])
        if c != 0:
            return c
        xi += 1
        yi += 1

def _compare_numerical(xl, yl, x, y, xi, yi):
    xn = _skip_while_from(xi, _is_digit, x, xl)
    yn = _skip_while_from(yi, _is_digit, y, yl)
    if xn - xi != yn - yi:
        return (xn - xi > yn - yi) - (xn - xi < yn - yi)
    return _loop_numerical(xl, yl, x, y, xi, yi, yn)

def _loop_numerical(xl, yl, x, y, xi, yi, yn):
    while yi != yn:
        c = (x[xi] > y[yi]) - (x[xi] < y[yi])
        if c != 0:
            return c
        xi += 1
        yi += 1
    return _loop_lexical(xl, yl, x, y, xi, yi)

def compare(x, y):
    if x == y:
        return 0
    lx, ly = len(x), len(y)
    rx = x.rfind('-')
    if rx < 0: rx = lx
    ry = y.rfind('-')
    if ry < 0: ry = ly
    c = _loop_lexical(rx, ry, x, y, 0, 0)
    if c != 0:
        return (c > 0) - (c < 0)
    c = _loop_lexical(lx, ly, x, y, min(rx + 1, lx), min(ry + 1, ly))
    return (c > 0) - (c < 0)

# opam file fields and required depends.
def fields(text):
    lines = text.splitlines(); i = 0
    while i < len(lines):
        m = re.match(r'([A-Za-z][A-Za-z0-9_-]*)\s*:(.*)$', lines[i])
        if not m:
            i += 1; continue
        name, body = m.group(1), m.group(2)
        depth = body.count('[') - body.count(']') + body.count('{') - body.count('}')
        j = i + 1
        while j < len(lines) and depth > 0:
            body += '\n' + lines[j]
            depth += lines[j].count('[') - lines[j].count(']')
            depth += lines[j].count('{') - lines[j].count('}')
            j += 1
        yield name, body
        i = j

ITEM = re.compile(r'"([^"]+)"\s*(?:\{([^{}]*)\})?', re.S)
WITH = re.compile(r'\bwith-(test|doc|dev-setup)\b')

def required_items(text):
    out = []
    for name, body in fields(text):
        if name != 'depends':
            continue
        for m in ITEM.finditer(body):
            filt = m.group(2) or ''
            if WITH.search(filt):
                continue
            out.append((m.group(1), filt))
    return out

# OCaml 5.5.1 support, including compiler variants.
def _strip_quote(s):
    return s[1:-1] if s.startswith('"') and s.endswith('"') else s

def _check(op, version):
    c = compare(OCAML, version)
    return {'>=': c >= 0, '>': c > 0, '<=': c <= 0, '<': c < 0,
            '=': c == 0, '!=': c != 0}[op]

TOK = re.compile(r'\s*(>=|<=|!=|>|<|=|&|\||!|\(|\)|"[^"]*"|[A-Za-z_][A-Za-z0-9_.+-]*)', re.S)

def _tokens(s):
    out, pos = [], 0
    while pos < len(s):
        m = TOK.match(s, pos)
        if not m:
            if s[pos:].strip() == '':
                break
            pos += 1; continue
        out.append(m.group(1)); pos = m.end()
    return out

class _Filter:
    def __init__(self, toks): self.t = toks; self.i = 0
    def peek(self): return self.t[self.i] if self.i < len(self.t) else None
    def next(self):
        v = self.peek(); self.i += 1; return v
    def parse(self): return self.or_()
    def or_(self):
        v = self.and_()
        while self.peek() == '|':
            self.next(); v = self.and_() or v
        return v
    def and_(self):
        v = self.unary()
        while self.peek() == '&':
            self.next(); v = self.unary() and v
        return v
    def unary(self):
        if self.peek() == '!':
            self.next(); return not self.unary()
        return self.atom()
    def atom(self):
        t = self.peek()
        if t == '(':
            self.next(); v = self.or_()
            if self.peek() == ')': self.next()
            return v
        if t in ('>=', '<=', '!=', '>', '<', '='):
            op = self.next()
            val = _strip_quote(self.next() or '0')
            return _check(op, val)
        if t is None:
            return True
        left = self.next()
        if self.peek() in ('>=', '<=', '!=', '>', '<', '='):
            self.next(); self.next()
            return True  # os/arch/etc.
        return left != 'false'

def _eval(f):
    if not f.strip():
        return True
    try:
        return _Filter(_tokens(f)).parse()
    except Exception:
        return True

OCAML_RE = re.compile(r'"(?:ocaml|ocaml-base-compiler|ocaml-variants|ocaml-system|ocaml-compiler)"\s*(?:\{([^{}]*)\})?', re.S)

def supports_551(text):
    found = []
    for name, body in fields(text):
        if name == 'depends':
            found += [m.group(1) or '' for m in OCAML_RE.finditer(body)]
    return not found or any(_eval(f) for f in found)

def supports_any(pkg, pdir):
    versions = [v for v in os.listdir(pdir) if os.path.isdir(os.path.join(pdir, v))]
    versions.sort(key=cmp_to_key(compare), reverse=True)
    for v in versions:
        try:
            text = open(os.path.join(pdir, v, 'opam'), encoding='utf-8', errors='replace').read()
        except OSError:
            continue
        if supports_551(text):
            return True
    return False

def opam_packages(path):
    if path:
        p = os.path.abspath(path)
        return os.path.join(p, 'packages') if os.path.isdir(os.path.join(p, 'packages')) else p
    root = os.path.join(tempfile.gettempdir(), f'opam-repository-{OPAM_COMMIT}')
    if not os.path.isdir(os.path.join(root, 'packages')):
        archive = root + '.tar.gz'
        urllib.request.urlretrieve(OPAM_URL, archive)
        with tarfile.open(archive) as t:
            t.extractall(tempfile.gettempdir())
    return os.path.join(root, 'packages')

def latest_version(pkg, pdir):
    versions = [v for v in os.listdir(pdir) if os.path.isdir(os.path.join(pdir, v))]
    best = versions[0]
    for v in versions[1:]:
        if compare(v[len(pkg) + 1:], best[len(pkg) + 1:]) > 0:
            best = v
    return best

def ranked_packages(pkgs):
    deps = {}
    texts = {}
    support = {}
    for pkg in sorted(os.listdir(pkgs)):
        pdir = os.path.join(pkgs, pkg)
        if not os.path.isdir(pdir):
            continue
        try:
            v = latest_version(pkg, pdir)
            text = open(os.path.join(pdir, v, 'opam'), encoding='utf-8', errors='replace').read()
        except OSError:
            continue
        texts[pkg] = text
        support[pkg] = supports_any(pkg, pdir)
        deps[pkg] = {d for d, _ in required_items(text) if d != pkg}
    rev = defaultdict(set)
    for pkg, ds in deps.items():
        for d in ds:
            rev[d].add(pkg)

    def transitive(target):
        seen = set()
        todo = list(rev[target])
        while todo:
            p = todo.pop()
            if p in seen:
                continue
            seen.add(p)
            todo.extend(rev[p])
        return len(seen)

    return sorted(((p, len(rev[p]), transitive(p)) for p in deps),
                  key=lambda x: (-x[1], -x[2], x[0])), texts, support

def skip_meta(pkg):
    return (pkg in META or pkg.startswith('conf-') or pkg.startswith('host-')
            or pkg.startswith('msys2') or pkg.startswith('ocaml-env-'))


