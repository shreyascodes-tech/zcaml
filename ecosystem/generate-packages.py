def apply_targets(package, unsupported):
    extra = TARGET_PATCHES.get(package)
    if not extra:
        return unsupported
    return ','.join(x for x in (unsupported, extra) if x)


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument('--top', type=int, default=500,
                        help='number of top packages to include (0 = all)')
    parser.add_argument('--output', default=os.path.join(HERE, 'packages.tsv'),
                        help='output TSV')
    args = parser.parse_args()
    if args.top < 0:
        raise SystemExit('--top must be >= 0')

    selected = TOP[:args.top] if args.top else TOP
    rows = []
    seen = set()
    for line in selected:
        package, group = line.rsplit(' ', 1)
        constraint = libraries = ppx = unsupported = ''
        if package in PATCHES:
            constraint, libraries, ppx, unsupported, group = PATCHES[package]
        unsupported = apply_targets(package, unsupported)
        rows.append([package, constraint, libraries, ppx, unsupported, group])
        seen.add(package)

    for package, group in EXTRA.items():
        if package in seen:
            continue
        constraint = libraries = ppx = unsupported = ''
        if package in PATCHES:
            constraint, libraries, ppx, unsupported, group = PATCHES[package]
        unsupported = apply_targets(package, unsupported)
        rows.append([package, constraint, libraries, ppx, unsupported, group])
        seen.add(package)

    with open(args.output, 'w', encoding='utf-8') as f:
        f.write(HEADER)
        for row in rows:
            f.write('\t'.join(row) + '\n')

    counts = {g: sum(1 for r in rows if r[5] == g) for g in GROUPS}
    print(f'{args.output}: {len(rows)} packages '
          f'({counts["ml-only"]} ml-only, {counts["c-stubs"]} c-stubs, '
          f'{counts["system-libs"]} system-libs)')


if __name__ == '__main__':
    main()
