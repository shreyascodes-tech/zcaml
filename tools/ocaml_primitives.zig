const std = @import("std");
const Io = std.Io;
const Manifest = @import("manifest.zig");
const Allocator = std.mem.Allocator;

const Primitives = struct {
    names: []const []const u8,
    declarations: []const []const u8,
};

pub fn main(init: std.process.Init) !void {
    const gpa = init.arena.allocator();
    const io = init.io;
    const argv = try init.minimal.args.toSlice(gpa);
    if (argv.len != 5) {
        std.log.err("usage: ocaml-primitives <manifest.zon> <source-dir> <primitives> <prims.c>", .{});
        return error.InvalidArguments;
    }

    const zon = try Io.Dir.cwd().readFileAlloc(io, argv[1], gpa, .unlimited);
    const manifest = try std.zon.parse.fromSliceAlloc(Manifest, gpa, try gpa.dupeZ(u8, zon), null, .{});
    const primitives = try collectPrimitives(gpa, io, argv[2], manifest.source_groups);
    try writePrimitives(io, argv[3], primitives.names);
    try writePrimsC(io, argv[4], primitives);
}

fn collectPrimitives(gpa: Allocator, io: Io, source_root: []const u8, groups: []const Manifest.SourceGroup) !Primitives {
    var names: std.ArrayList([]const u8) = .empty;
    var declarations: std.ArrayList([]const u8) = .empty;
    for (groups) |group| {
        if (!Manifest.isBytecodeRuntimeGroup(group.name)) continue;
        for (group.files) |path| {
            const source_path = try std.fs.path.join(gpa, &.{ source_root, path });
            const source = try Io.Dir.cwd().readFileAlloc(io, source_path, gpa, .unlimited);
            try scanSource(gpa, source, &names, &declarations);
        }
    }
    std.mem.sort([]const u8, names.items, {}, lessThan);

    // The same primitive can occur in multiple conditional definitions.
    var unique_names: std.ArrayList([]const u8) = .empty;
    for (names.items) |name| {
        if (unique_names.items.len > 0 and std.mem.eql(u8, name, unique_names.items[unique_names.items.len - 1])) continue;
        try unique_names.append(gpa, name);
    }
    return .{ .names = try unique_names.toOwnedSlice(gpa), .declarations = try declarations.toOwnedSlice(gpa) };
}

fn scanSource(gpa: Allocator, source: []const u8, names: *std.ArrayList([]const u8), declarations: *std.ArrayList([]const u8)) !void {
    var lines = std.mem.splitScalar(u8, source, '\n');
    var declaration: std.ArrayList(u8) = .empty;
    var in_declaration = false;
    while (lines.next()) |line| {
        if (!in_declaration) {
            const prefix = "CAMLprim value ";
            if (!std.mem.startsWith(u8, line, prefix)) continue;
            const tail = line[prefix.len..];
            var name = std.mem.tokenizeAny(u8, tail, " (\t\r");
            try names.append(gpa, name.next() orelse return error.InvalidPrimitive);
            try declaration.appendSlice(gpa, "CAMLextern value ");
            try declaration.appendSlice(gpa, tail);
            in_declaration = true;
        } else {
            try declaration.append(gpa, '\n');
            try declaration.appendSlice(gpa, line);
        }
        if (std.mem.indexOfScalar(u8, declaration.items, ')')) |end| {
            const signature = try std.fmt.allocPrint(gpa, "{s};\n", .{declaration.items[0 .. end + 1]});
            try declarations.append(gpa, signature);
            declaration.clearRetainingCapacity();
            in_declaration = false;
        }
    }
    if (in_declaration) return error.InvalidPrimitive;
}

fn writePrimitives(io: Io, output_path: []const u8, names: []const []const u8) !void {
    const primitives_file = try Io.Dir.cwd().createFile(io, output_path, .{});
    defer primitives_file.close(io);
    var primitives_buffer: [4096]u8 = undefined;
    var primitives_writer = primitives_file.writer(io, &primitives_buffer);
    for (names) |name| try primitives_writer.interface.print("{s}\n", .{name});
    try primitives_writer.flush();
}

fn writePrimsC(io: Io, output_path: []const u8, primitives: Primitives) !void {
    const prims_file = try Io.Dir.cwd().createFile(io, output_path, .{});
    defer prims_file.close(io);
    var prims_buffer: [4096]u8 = undefined;
    var prims_writer = prims_file.writer(io, &prims_buffer);
    const writer = &prims_writer.interface;
    try writer.writeAll(
        "/* Generated by tools/ocaml_primitives.zig */\n" ++
            "#define CAML_INTERNALS\n" ++
            "#include \"caml/mlvalues.h\"\n" ++
            "#include \"caml/prims.h\"\n" ++
            "#include \"caml/startup.h\"\n" ++
            "#include \"build_config.h\"\n\n",
    );
    for (primitives.declarations) |declaration| try writer.writeAll(declaration);
    try writer.writeAll("\nconst c_primitive caml_builtin_cprim[] = {\n");

    for (primitives.names) |name| {
        try writer.print("  (c_primitive) &{s},\n", .{name});
    }
    try writer.writeAll("  0 };\n\nconst char * const caml_names_of_builtin_cprim[] = {\n");
    for (primitives.names) |name| {
        try writer.print("  \"{s}\",\n", .{name});
    }
    try writer.writeAll(
        "  0 };\n\n" ++
            "const enum caml_byte_program_mode caml_byte_program_mode = STANDARD;\n" ++
            "const char_os *caml_runtime_standard_library_default = OCAML_STDLIB_DIR;\n",
    );
    try prims_writer.flush();
}

fn lessThan(_: void, a: []const u8, b: []const u8) bool {
    return std.mem.order(u8, a, b) == .lt;
}
