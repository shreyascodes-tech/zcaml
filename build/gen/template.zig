//! The two template styles autoconf uses, driven by a struct with one field
//! per variable:
//!
//!   - `.undef` (`AC_CONFIG_HEADERS`): each `#undef NAME` line becomes a
//!     `#define`, or a commented-out `#undef` for `false`/`null`.
//!   - `.at` (`AC_CONFIG_FILES`): each `@NAME@` is replaced by the value as an
//!     OCaml literal.
//!
//! `check` validates a template against the struct and reports which fields
//! it references; `Rendered` then writes it and can only fail on I/O, which
//! keeps it a plain `format` value.

const std = @import("std");
const Writer = std.Io.Writer;

pub const Style = enum { undef, at };

pub fn Used(comptime T: type) type {
    return std.EnumSet(std.meta.FieldEnum(T));
}

pub const Diagnostic = struct { name: []const u8 = "" };

pub fn check(comptime T: type, style: Style, text: []const u8, diag: *Diagnostic) error{UnknownVariable}!Used(T) {
    const Field = std.meta.FieldEnum(T);
    var used: Used(T) = .initEmpty();
    var it: Iterator = .{ .style = style, .text = text };
    while (it.next()) |piece| switch (piece) {
        .literal, .configure_input => {},
        .variable => |name| {
            const field = std.meta.stringToEnum(Field, name) orelse {
                diag.name = name;
                return error.UnknownVariable;
            };
            used.insert(field);
        },
    };
    return used;
}

/// Only valid after `check` succeeded. `style` is comptime so that only the
/// value types each style supports get instantiated (optionals are
/// `.undef`-only).
pub fn Rendered(comptime T: type, comptime style: Style) type {
    return struct {
        text: []const u8,
        values: T,
        input_name: []const u8,

        pub fn format(r: @This(), w: *Writer) Writer.Error!void {
            const Field = std.meta.FieldEnum(T);
            if (style == .undef) try w.print("/* Generated by zcaml from {s}. */\n", .{r.input_name});
            var it: Iterator = .{ .style = style, .text = r.text };
            while (it.next()) |piece| switch (piece) {
                .literal => |s| try w.writeAll(s),
                .configure_input => try w.print("Generated by zcaml from {s}. Do not edit.", .{r.input_name}),
                .variable => |name| switch (std.meta.stringToEnum(Field, name).?) {
                    inline else => |f| switch (style) {
                        .undef => try writeDefine(w, @tagName(f), @field(r.values, @tagName(f))),
                        .at => try writeValue(w, .ocaml, @field(r.values, @tagName(f))),
                    },
                },
            };
        }
    };
}

/// C string literal. TODO: Windows needs UTF-16 (`L"..."`), like
/// `sak encode-C-utf16-literal`.
pub fn writeCLiteral(w: *Writer, s: []const u8) Writer.Error!void {
    try w.writeByte('"');
    for (s) |c| switch (c) {
        '\\' => try w.writeAll("\\\\"),
        '"' => try w.writeAll("\\\""),
        '\n' => try w.writeAll("\\n"),
        '\r' => try w.writeAll("\\r"),
        else => try w.writeByte(c),
    };
    try w.writeByte('"');
}

pub fn Quoted(comptime T: type) type {
    return struct {
        v: T,
        pub fn format(q: @This(), w: *Writer) Writer.Error!void {
            if (T == []const u8) return writeCLiteral(w, q.v);
            try w.writeByte('"');
            try w.print("{f}", .{q.v});
            try w.writeByte('"');
        }
    };
}

/// Non-empty parts joined with single spaces.
pub fn Join(comptime n: usize) type {
    return struct {
        parts: [n][]const u8,
        pub fn format(j: @This(), w: *Writer) Writer.Error!void {
            var first = true;
            for (j.parts) |p| {
                if (p.len == 0) continue;
                if (!first) try w.writeByte(' ');
                first = false;
                try w.writeAll(p);
            }
        }
    };
}

/// `{|...|}` delimiter id: `n` copies of `o`.
pub const Qs = struct {
    n: u8,
    pub fn format(q: Qs, w: *Writer) Writer.Error!void {
        try w.splatByteAll('o', q.n);
    }
};

/// `OCAML_QUOTED_STRING_ID`: shortest `o*` such that no value of `s` (other
/// than `QS` itself) contains `|o*}`.
pub fn quotedStringId(comptime T: type, s: *const T) error{ValueTooLong}!Qs {
    var closer_buf: [16]u8 = undefined;
    var n: u8 = 0;
    next: while (n + 2 <= closer_buf.len) : (n += 1) {
        closer_buf[0] = '|';
        @memset(closer_buf[1 .. n + 1], 'o');
        closer_buf[n + 1] = '}';
        const closer = closer_buf[0 .. n + 2];
        inline for (@typeInfo(T).@"struct".fields) |f| {
            if (comptime std.mem.eql(u8, f.name, "QS")) continue;
            var buf: [4096]u8 = undefined;
            var w: Writer = .fixed(&buf);
            writeValue(&w, .ocaml, @field(s, f.name)) catch return error.ValueTooLong;
            if (std.mem.find(u8, w.buffered(), closer) != null) continue :next;
        }
        return .{ .n = n };
    }
    return error.ValueTooLong;
}

const Piece = union(enum) {
    literal: []const u8,
    variable: []const u8,
    /// autoconf's `@configure_input@`: a banner, not a value.
    configure_input,
};

/// Shared by `check` and `Rendered` so they cannot disagree about what counts
/// as a variable.
const Iterator = struct {
    style: Style,
    text: []const u8,
    i: usize = 0,
    pending_newline: bool = false,

    fn next(it: *Iterator) ?Piece {
        if (it.i >= it.text.len) return null;
        return switch (it.style) {
            .undef => it.nextUndef(),
            .at => it.nextAt(),
        };
    }

    fn nextUndef(it: *Iterator) ?Piece {
        if (it.pending_newline) {
            it.pending_newline = false;
            it.i += 1;
            return .{ .literal = "\n" };
        }
        const rest = it.text[it.i..];
        const nl = std.mem.indexOfScalar(u8, rest, '\n') orelse rest.len;
        const line = rest[0..nl];
        if (undefName(line)) |name| {
            it.i += nl;
            it.pending_newline = nl < rest.len;
            return .{ .variable = name };
        }
        const end = if (nl < rest.len) nl + 1 else nl;
        it.i += end;
        return .{ .literal = rest[0..end] };
    }

    fn nextAt(it: *Iterator) ?Piece {
        const text = it.text;
        const at = std.mem.findScalarPos(u8, text, it.i, '@') orelse {
            const lit = text[it.i..];
            it.i = text.len;
            return .{ .literal = lit };
        };
        if (at > it.i) {
            const lit = text[it.i..at];
            it.i = at;
            return .{ .literal = lit };
        }
        var end = at + 1;
        while (end < text.len and isIdentChar(text[end])) end += 1;
        if (end == at + 1 or end >= text.len or text[end] != '@') {
            it.i = at + 1;
            return .{ .literal = "@" };
        }
        const name = text[at + 1 .. end];
        it.i = end + 1;
        if (std.mem.eql(u8, name, "configure_input")) return .configure_input;
        return .{ .variable = name };
    }
};

fn undefName(line: []const u8) ?[]const u8 {
    var rest = std.mem.trimStart(u8, line, " \t");
    if (!std.mem.startsWith(u8, rest, "#")) return null;
    rest = std.mem.trimStart(u8, rest[1..], " \t");
    if (!std.mem.startsWith(u8, rest, "undef")) return null;
    rest = std.mem.trim(u8, rest["undef".len..], " \t\r");
    if (rest.len == 0 or std.mem.findAny(u8, rest, " \t") != null) return null;
    return rest;
}

fn isIdentChar(c: u8) bool {
    return std.ascii.isAlphanumeric(c) or c == '_';
}

fn writeDefine(w: *Writer, name: []const u8, value: anytype) Writer.Error!void {
    switch (@typeInfo(@TypeOf(value))) {
        .optional => return if (value) |v| writeDefine(w, name, v) else w.print("/* #undef {s} */", .{name}),
        .bool => if (!value) return w.print("/* #undef {s} */", .{name}),
        else => {},
    }
    try w.print("#define {s} ", .{name});
    try writeValue(w, .c, value);
}

const Syntax = enum { c, ocaml };

fn writeValue(w: *Writer, comptime syntax: Syntax, value: anytype) Writer.Error!void {
    const T = @TypeOf(value);
    switch (@typeInfo(T)) {
        .bool => try w.writeAll(switch (syntax) {
            .c => if (value) "1" else "0",
            .ocaml => if (value) "true" else "false",
        }),
        .int, .comptime_int => try w.print("{d}", .{value}),
        .pointer => |p| switch (p.size) {
            .slice => {
                if (p.child != u8) @compileError("unsupported value type " ++ @typeName(T));
                try w.writeAll(value);
            },
            .one => try writeValue(w, syntax, value.*),
            else => @compileError("unsupported value type " ++ @typeName(T)),
        },
        .array => |a| {
            if (a.child != u8) @compileError("unsupported value type " ++ @typeName(T));
            try w.writeAll(&value);
        },
        .@"struct", .@"union", .@"enum" => {
            if (!@hasDecl(T, "format")) @compileError(@typeName(T) ++ " has no format method");
            try w.print("{f}", .{value});
        },
        else => @compileError("unsupported value type " ++ @typeName(T)),
    }
}
