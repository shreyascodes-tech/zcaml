//! `ocaml-gen sources`: see `Sources.zig` for the schema.

const std = @import("std");
const Io = std.Io;

const Sources = @import("Sources");
const cli = @import("cli.zig");
const depend = @import("depend.zig");
const Makefile = @import("makefile.zig");
const fail = cli.fail;

const Args = struct {
    src: []const u8 = undefined,
    out: []const u8 = undefined,
    ocaml_hash: []const u8 = undefined,
};

/// Stand-ins for what `Makefile.build_config` would define; the lists are
/// extracted with the markers in place and split afterwards.
const platform_marker = "@PLATFORM@";
const tsan_marker = "@TSAN@";

pub fn run(io: Io, gpa: std.mem.Allocator, argv: *std.process.Args.Iterator) !void {
    const args = try cli.parseArgs(Args, gpa, argv);

    var arena_state: std.heap.ArenaAllocator = .init(gpa);
    defer arena_state.deinit();
    const arena = arena_state.allocator();

    const src = Io.Dir.cwd().openDir(io, args.src, .{}) catch |err|
        return fail("{s}: {t}", .{ args.src, err });
    defer src.close(io);

    var vars: Makefile = .{ .arena = arena };
    try vars.seed("UNIX_OR_WIN32", platform_marker);
    try vars.seed("TSAN_NATIVE_RUNTIME_C_SOURCES", tsan_marker);
    // Per-target backend files are selected by the build, not listed here.
    try vars.seed("arch_specific_SOURCES", "");
    // Windows-only.
    try vars.seed("ocamlyacc_WSTR_MODULE", "");
    for ([_][]const u8{ "Makefile", "stdlib/StdlibModules" }) |path| {
        const text = try readSrc(io, arena, src, path);
        try vars.parse(text);
    }

    var lists: Lists = .{ .vars = &vars };

    const runtime_common = try lists.get("runtime_COMMON_C_SOURCES");
    const runtime_native_only = try lists.get("runtime_NATIVE_ONLY_C_SOURCES");
    const stdlib_basenames = try lists.get("STDLIB_MODULE_BASENAMES");

    const sources: Sources = .{
        .ocaml_hash = args.ocaml_hash,
        .runtime = .{
            .common = try without(arena, runtime_common, platform_marker),
            .platform = .{ .unix = "unix", .win32 = "win32" },
            .bytecode_only = try lists.get("runtime_BYTECODE_ONLY_C_SOURCES"),
            .native_only = try without(arena, runtime_native_only, tsan_marker),
        },
        .stdlib = .{
            .basenames = stdlib_basenames,
            .modules = try prefixModules(arena, stdlib_basenames),
        },
        .compilerlibs = .{
            .ocamlcommon = try lists.get("ocamlcommon_SOURCES"),
            .ocamlbytecomp = try lists.get("ocamlbytecomp_SOURCES"),
            .ocamloptcomp = try lists.get("ocamloptcomp_SOURCES"),
            .ocamltoplevel = try lists.get("ocamltoplevel_SOURCES"),
        },
        .programs = .{
            .ocamlc = try lists.get("ocamlc_SOURCES"),
            .ocamlopt = try lists.get("ocamlopt_SOURCES"),
            .ocaml = try lists.get("ocaml_SOURCES"),
            .ocamllex = try lists.get("ocamllex_SOURCES"),
        },
        .yacc = try stripPrefix(arena, try lists.get("ocamlyacc_OTHER_MODULES"), "yacc/"),
        .depend = .{
            .compiler = try objectRules(io, arena, src, ".depend"),
            .stdlib = try objectRules(io, arena, src, "stdlib/.depend"),
        },
    };

    const out = Io.Dir.cwd().createFile(io, args.out, .{}) catch |err|
        return fail("{s}: {t}", .{ args.out, err });
    defer out.close(io);
    var buf: [64 * 1024]u8 = undefined;
    var fw = out.writer(io, &buf);
    try fw.interface.writeAll("// Generated by `zig build gen` from the OCaml tree's Makefiles. Do not edit.\n");
    try std.zon.stringify.serialize(sources, .{}, &fw.interface);
    try fw.interface.writeByte('\n');
    try fw.interface.flush();
}

const Lists = struct {
    vars: *Makefile,

    fn get(l: Lists, name: []const u8) ![]const []const u8 {
        var diag: Makefile.Diagnostic = .{};
        return l.vars.words(name, &diag) catch |err| switch (err) {
            error.Undefined => fail("{s}: references undefined variable '{s}' (seed it?)", .{ name, diag.name }),
            error.Unsupported => fail("{s}: unsupported make construct '{s}'", .{ name, diag.name }),
            error.OutOfMemory => error.OutOfMemory,
        };
    }
};

fn readSrc(io: Io, arena: std.mem.Allocator, src: Io.Dir, path: []const u8) ![]u8 {
    return src.readFileAlloc(io, path, arena, .unlimited) catch |err|
        return fail("{s}: {t}", .{ path, err });
}

fn without(arena: std.mem.Allocator, list: []const []const u8, word: []const u8) ![]const []const u8 {
    var out: std.ArrayList([]const u8) = .empty;
    var found = false;
    for (list) |w| {
        if (std.mem.eql(u8, w, word)) {
            found = true;
            continue;
        }
        try out.append(arena, w);
    }
    if (!found) return fail("expected '{s}' in list", .{word});
    return out.toOwnedSlice(arena);
}

fn stripPrefix(arena: std.mem.Allocator, list: []const []const u8, prefix: []const u8) ![]const []const u8 {
    const out = try arena.alloc([]const u8, list.len);
    for (out, list) |*o, w| {
        if (!std.mem.startsWith(u8, w, prefix)) return fail("'{s}' lacks prefix '{s}'", .{ w, prefix });
        o.* = w[prefix.len..];
    }
    return out;
}

/// `PREFIX_MODULE` from `stdlib/StdlibModules`; upstream is a recursive
/// `$(call CAPITALIZE ...)`, which is more make than `makefile.zig` supports.
fn prefixModules(arena: std.mem.Allocator, basenames: []const []const u8) ![]const []const u8 {
    const out = try arena.alloc([]const u8, basenames.len);
    for (out, basenames) |*o, name| {
        if (std.mem.eql(u8, name, "stdlib") or std.mem.startsWith(u8, name, "camlinternal")) {
            o.* = name;
        } else {
            const m = try std.fmt.allocPrint(arena, "stdlib__{s}", .{name});
            m["stdlib__".len] = std.ascii.toUpper(m["stdlib__".len]);
            o.* = m;
        }
    }
    return out;
}

fn objectRules(io: Io, arena: std.mem.Allocator, src: Io.Dir, path: []const u8) ![]const Sources.Rule {
    const text = try readSrc(io, arena, src, path);
    const rules = depend.parse(arena, text) catch |err| return fail("{s}: {t}", .{ path, err });
    var out: std.ArrayList(Sources.Rule) = .empty;
    for (rules) |r| {
        const ext = std.fs.path.extension(r.target);
        if (!(std.mem.eql(u8, ext, ".cmi") or std.mem.eql(u8, ext, ".cmo") or std.mem.eql(u8, ext, ".cmx"))) continue;
        try out.append(arena, .{ .target = r.target, .deps = r.deps });
    }
    return out.toOwnedSlice(arena);
}
