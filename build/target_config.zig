const std = @import("std");

pub const TargetConfig = struct {
    resolved: std.Build.ResolvedTarget,
    arch: []const u8,
    model: []const u8,
    system: []const u8,
    os_type: []const u8,
    unix_or_win32: []const u8,
    triplet: []const u8,
    arch64: bool,
    big_endian: bool,
    is_windows: bool,
    is_macos: bool,
    is_linux: bool,
    is_bsd: bool,
    is_elf: bool,
    bytecode_runtime_id: []const u8 = "a100",
    native_runtime_id: []const u8 = "a100",
    zinc_runtime_id: []const u8 = "a100",

    pub fn fromTarget(b: *std.Build, resolved: std.Build.ResolvedTarget) TargetConfig {
        const t = resolved.result;
        const arch64 = t.ptrBitWidth() == 64;
        const big_endian = t.cpu.arch.endian() == .big;
        const is_windows = t.os.tag == .windows;
        const is_macos = t.os.tag.isDarwin();
        const is_linux = t.os.tag == .linux;
        const is_bsd = switch (t.os.tag) {
            .freebsd, .openbsd, .netbsd, .dragonfly => true,
            else => false,
        };
        const is_elf = t.ofmt == .elf;

        const arch: []const u8 = switch (t.cpu.arch) {
            .x86_64 => "amd64",
            .aarch64, .aarch64_be => "arm64",
            .riscv64 => "riscv",
            .powerpc64, .powerpc64le => "power",
            .s390x => "s390x",
            .x86 => "i386",
            .arm, .armeb => "arm",
            else => "none",
        };

        const model: []const u8 = switch (t.cpu.arch) {
            .riscv64 => "riscv64",
            .powerpc64le => "ppc64le",
            .powerpc64 => "ppc64",
            .s390x => "z10",
            else => "default",
        };

        const system: []const u8 = switch (t.os.tag) {
            .linux => "linux",
            .macos, .ios, .tvos, .watchos, .visionos => "macosx",
            .windows => if (t.abi == .msvc) "win64" else "mingw64",
            .freebsd => "freebsd",
            .openbsd => "openbsd",
            .netbsd => "netbsd",
            .dragonfly => "dragonfly",
            .illumos => "solaris",
            .haiku => "beos",
            else => "unknown",
        };

        const os_type: []const u8 = if (is_windows) "Win32" else "Unix";
        const unix_or_win32: []const u8 = if (is_windows) "win32" else "unix";

        const arch_str = @tagName(t.cpu.arch);
        const triplet = switch (t.os.tag) {
            .linux => b.fmt("{s}-pc-linux-{s}", .{
                arch_str,
                if (t.abi.isMusl()) "musl" else "gnu",
            }),
            .macos => b.fmt("{s}-apple-darwin", .{arch_str}),
            .windows => if (t.abi == .msvc)
                b.fmt("{s}-pc-windows", .{arch_str})
            else
                b.fmt("{s}-w64-mingw32", .{arch_str}),
            .freebsd => b.fmt("{s}-unknown-freebsd", .{arch_str}),
            .openbsd => b.fmt("{s}-unknown-openbsd", .{arch_str}),
            .netbsd => b.fmt("{s}-unknown-netbsd", .{arch_str}),
            else => b.fmt("{s}-unknown-{s}", .{ arch_str, @tagName(t.os.tag) }),
        };

        return .{
            .resolved = resolved,
            .arch = arch,
            .model = model,
            .system = system,
            .os_type = os_type,
            .unix_or_win32 = unix_or_win32,
            .triplet = triplet,
            .arch64 = arch64,
            .big_endian = big_endian,
            .is_windows = is_windows,
            .is_macos = is_macos,
            .is_linux = is_linux,
            .is_bsd = is_bsd,
            .is_elf = is_elf,
        };
    }

    pub fn runtimeAsmFile(self: TargetConfig) ?[]const u8 {
        if (self.is_windows and self.resolved.result.abi == .msvc) {
            if (std.mem.eql(u8, self.arch, "amd64")) return "amd64nt.asm";
            return null;
        }
        if (std.mem.eql(u8, self.arch, "amd64")) return "amd64.S";
        if (std.mem.eql(u8, self.arch, "arm64")) return "arm64.S";
        if (std.mem.eql(u8, self.arch, "riscv")) return "riscv.S";
        if (std.mem.eql(u8, self.arch, "power")) return "power.S";
        if (std.mem.eql(u8, self.arch, "s390x")) return "s390x.S";
        return null;
    }

    pub fn generateMH(self: TargetConfig, b: *std.Build) []const u8 {
        var out: std.ArrayList(u8) = .empty;
        const alloc = b.allocator;

        out.appendSlice(alloc, "/* Generated by zcaml */\n#ifndef CAML_M_H\n#define CAML_M_H\n\n") catch @panic("OOM");
        if (self.arch64) out.appendSlice(alloc, "#define ARCH_SIXTYFOUR 1\n") catch @panic("OOM");
        if (self.big_endian) out.appendSlice(alloc, "#define ARCH_BIG_ENDIAN 1\n") catch @panic("OOM");

        const has_code32 = (std.mem.eql(u8, self.arch, "amd64") and (self.is_linux or self.is_macos)) or
            (std.mem.eql(u8, self.arch, "arm64") and self.is_macos);
        if (has_code32) out.appendSlice(alloc, "#define HAS_ARCH_CODE32 1\n") catch @panic("OOM");

        const sizeof_long: u8 = if (self.is_windows or !self.arch64) 4 else 8;
        const sizeof_ptr: u8 = if (self.arch64) 8 else 4;

        out.appendSlice(alloc, b.fmt(
            \\#define SIZEOF_INT 4
            \\#define SIZEOF_LONG {d}
            \\#define SIZEOF_PTR {d}
            \\#define SIZEOF_SHORT 2
            \\#define SIZEOF_LONGLONG 8
            \\#define HEADER_RESERVED_BITS 0
            \\#define NO_NAKED_POINTERS 1
            \\#define CAML_SAFE_STRING 1
            \\#define FLAT_FLOAT_ARRAY 1
            \\#define SUPPORTS_ALIGNED_ATTRIBUTE 1
            \\#define SUPPORTS_TREE_VECTORIZE 1
            \\
        , .{ sizeof_long, sizeof_ptr })) catch @panic("OOM");

        if (!self.is_windows) {
            out.appendSlice(alloc, "#define ASM_CFI_SUPPORTED 1\n") catch @panic("OOM");
        }
        if (self.is_elf) {
            out.appendSlice(alloc, "#define ASM_SIZE_TYPE_DIRECTIVES 1\n") catch @panic("OOM");
            out.appendSlice(alloc, "#define FUNCTION_SECTIONS 1\n") catch @panic("OOM");
        }
        if (self.is_linux and self.is_elf) {
            out.appendSlice(alloc, "#define WITH_NONEXECSTACK_NOTE 1\n") catch @panic("OOM");
        }
        if (self.resolved.result.os.tag == .openbsd) {
            out.appendSlice(alloc, "#define USE_MMAP_MAP_STACK 1\n") catch @panic("OOM");
        }

        out.appendSlice(alloc, "\n#endif /* CAML_M_H */\n") catch @panic("OOM");
        return out.items;
    }

