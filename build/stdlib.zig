const std = @import("std");
const TargetConfig = @import("target_config.zig").TargetConfig;
const SourceInfo = @import("source_info.zig").SourceInfo;
const RuntimeArtifacts = @import("runtime.zig").RuntimeArtifacts;
const Tools = @import("tools/root.zig");
const HeaderFormat = @import("tools/build_stdlib.zig").HeaderFormat;

pub const StdlibArtifacts = struct {
    stdlib_dir: std.Build.LazyPath,
    meta_file: std.Build.LazyPath,
    header_format: HeaderFormat,
};

pub const BuildStdlibOptions = struct {
    src_info: SourceInfo,
    target_cfg: TargetConfig,
    target_rt: RuntimeArtifacts,
    build_ocamlrun: *std.Build.Step.Compile,
    optimize: std.builtin.OptimizeMode,
    target_bindir: []const u8 = "/usr/local/bin",
};

pub fn buildStdlib(
    b: *std.Build,
    ocaml_dep: *std.Build.Dependency,
    options: BuildStdlibOptions,
) !StdlibArtifacts {
    const src_info = options.src_info;
    const cfg = options.target_cfg;
    const v = src_info.version;

    // 1. Parse module basenames from stdlib/StdlibModules and COMPFLAGS from stdlib/Makefile
    const module_basenames = src_info.parseMakefileListFromFile(
        "stdlib/StdlibModules",
        "STDLIB_MODULE_BASENAMES",
        &.{},
    );
    const compflags = src_info.parseMakefileListFromFile(
        "stdlib/Makefile",
        "COMPFLAGS",
        &.{},
    );

    // 2. Render stdlib/sys.ml and stdlib/META from upstream .in templates with strict safety checks
    const release_extra_ml = if (v.extra.len == 0)
        "None"
    else
        b.fmt("Some ({s}, \"{s}\")", .{
            if (std.mem.eql(u8, v.extra_prefix, "+")) "Plus" else "Tilde",
            v.extra,
        });

    const sys_ml_content = src_info.renderAtTemplate("stdlib/sys.ml.in", &.{
        .{ .name = "configure_input", .value = "Generated by zcaml from stdlib/sys.ml.in" },
        .{ .name = "VERSION", .value = v.version_string },
        .{ .name = "OCAML_DEVELOPMENT_VERSION", .value = if (v.dev_version) "true" else "false" },
        .{ .name = "OCAML_VERSION_MAJOR", .value = b.fmt("{d}", .{v.major}) },
        .{ .name = "OCAML_VERSION_MINOR", .value = b.fmt("{d}", .{v.minor}) },
        .{ .name = "OCAML_VERSION_PATCHLEVEL", .value = b.fmt("{d}", .{v.patchlevel}) },
        .{ .name = "OCAML_RELEASE_EXTRA", .value = release_extra_ml },
    });

    const meta_content = src_info.renderAtTemplate("stdlib/META.in", &.{
        .{ .name = "configure_input", .value = "Generated by zcaml from stdlib/META.in" },
        .{ .name = "VERSION", .value = v.version_string },
    });

    const wf = b.addWriteFiles();
    const sys_ml_lp = wf.add("sys.ml", sys_ml_content);
    const meta_lp = wf.add("META", meta_content);

    // 3. Determine header format and build tmpheader.exe for bytecode launcher
    const is_5_5_or_newer = v.sem_ver.order(.{ .major = 5, .minor = 5, .patch = 0 }) != .lt;
    const is_5_2_or_newer = v.sem_ver.order(.{ .major = 5, .minor = 2, .patch = 0 }) != .lt;

    const header_format: HeaderFormat = if (is_5_5_or_newer)
        .launch_info_5_5
    else if (is_5_2_or_newer)
        .launch_info_5_2
    else
        .camlheader_5_0;

    const header_exe = buildTmpHeaderExe(b, ocaml_dep, options, header_format);

    // 4. Run build_stdlib tool command using build-host ocamlrun + boot/ocamlc
    var cmd = Tools.Command{
        .build_stdlib = .{
            .ocamlrun = .of(options.build_ocamlrun.getEmittedBin()),
            .ocamlc = .of(ocaml_dep.path("boot/ocamlc")),
            .primitives = .of(options.target_rt.primitives),
            .stdlib_src_dir = .of(ocaml_dep.path("stdlib")),
            .compflags_script = .of(ocaml_dep.path("stdlib/Compflags")),
            .depend_file = .of(ocaml_dep.path("stdlib/.depend")),
            .sys_ml = .of(sys_ml_lp),
            .meta_file = .of(meta_lp),
            .header_exe = .of(header_exe.getEmittedBin()),
            .header_format = header_format,
            .is_windows_target = cfg.is_windows,
            .target_bindir = options.target_bindir,
            .compflags = compflags,
            .module_basenames = module_basenames,
            .out_dir = .of("stdlib"),
        },
    };
    _ = cmd.run(b);

    return .{
        .stdlib_dir = cmd.build_stdlib.out_dir.lazyPath(),
        .meta_file = meta_lp,
        .header_format = header_format,
    };
}

fn buildTmpHeaderExe(
    b: *std.Build,
    ocaml_dep: *std.Build.Dependency,
    options: BuildStdlibOptions,
    header_format: HeaderFormat,
) *std.Build.Step.Compile {
    const cfg = options.target_cfg;
    const headers_dir = options.target_rt.headers_dir;
    const headers_caml_dir = headers_dir.path(b, "caml");

    const header_c_subpath: []const u8 = if (cfg.is_windows and header_format != .launch_info_5_5)
        "stdlib/headernt.c"
    else
        "stdlib/header.c";

    var cflags: std.ArrayList([]const u8) = .empty;
    cflags.appendSlice(b.allocator, &.{
        "-Os",
        "-fno-strict-aliasing",
        "-fwrapv",
        "-fno-sanitize=undefined",
    }) catch @panic("OOM");

    if (header_format == .camlheader_5_0) {
        cflags.append(b.allocator, "-DRUNTIME_NAME=\"ocamlrun\"") catch @panic("OOM");
    }

    if (cfg.is_windows) {
        cflags.appendSlice(b.allocator, &.{
            "-DUNICODE",
            "-D_UNICODE",
            "-DWINDOWS_UNICODE=1",
        }) catch @panic("OOM");
        if (header_format == .launch_info_5_5) {
            cflags.append(b.allocator, "-DwmainCRTStartup=wmain") catch @panic("OOM");
        }
    }

    const tmpheader = b.addExecutable(.{
        .name = "tmpheader",
        .root_module = b.createModule(.{
            .target = cfg.resolved,
            .optimize = .ReleaseSmall,
            .strip = true,
            .link_libc = true,
        }),
    });
    tmpheader.root_module.addIncludePath(headers_dir);
    tmpheader.root_module.addIncludePath(headers_caml_dir);
    tmpheader.root_module.addIncludePath(ocaml_dep.path("runtime"));
    tmpheader.root_module.addCSourceFile(.{
        .file = ocaml_dep.path(header_c_subpath),
        .flags = cflags.items,
    });
    if (cfg.is_windows) {
        tmpheader.mingw_unicode_entry_point = true;
    }

    return tmpheader;
}
