const std = @import("std");
const TargetConfig = @import("target_config.zig").TargetConfig;
const SourceInfo = @import("source_info.zig").SourceInfo;
const Manifest = @import("manifests/manifest.zig");
const StdlibUnit = Manifest.StdlibUnit;
const RuntimeArtifacts = @import("runtime.zig").RuntimeArtifacts;
const Tools = @import("tools/root.zig");
pub const HeaderFormat = @import("tools/gen_ocaml_sources.zig").HeaderFormat;

pub const StdlibArtifacts = struct {
    stdlib_dir: std.Build.LazyPath,
    meta_file: std.Build.LazyPath,
    unix_labels_mli: std.Build.LazyPath,
    header_format: HeaderFormat,
};

pub const BuildStdlibOptions = struct {
    src_info: SourceInfo,
    target_cfg: TargetConfig,
    target_rt: RuntimeArtifacts,
    build_ocamlrun: *std.Build.Step.Compile,
    optimize: std.builtin.OptimizeMode,
    target_bindir: []const u8 = "/usr/local/bin",
};

pub fn buildStdlib(
    b: *std.Build,
    ocaml_dep: *std.Build.Dependency,
    options: BuildStdlibOptions,
) !StdlibArtifacts {
    const src_info = options.src_info;
    const m = src_info.manifest;
    const cfg = options.target_cfg;
    const v = src_info.version;

    // 1. Render stdlib/sys.ml and stdlib/META from upstream .in templates
    const release_extra = if (v.extra.len == 0)
        "None"
    else blk: {
        const prefix_variant = if (std.mem.eql(u8, v.extra_prefix, "~")) "Tilde" else "Plus";
        break :blk b.fmt("Some ({s}, \"{s}\")", .{ prefix_variant, v.extra });
    };

    const sys_ml_content = src_info.renderAtTemplate("stdlib/sys.ml.in", &.{
        .{ .name = "configure_input", .value = "Generated by zcaml from stdlib/sys.ml.in" },
        .{ .name = "VERSION", .value = v.version_string },
        .{ .name = "OCAML_DEVELOPMENT_VERSION", .value = if (v.dev_version) "true" else "false" },
        .{ .name = "OCAML_VERSION_MAJOR", .value = b.fmt("{d}", .{v.major}) },
        .{ .name = "OCAML_VERSION_MINOR", .value = b.fmt("{d}", .{v.minor}) },
        .{ .name = "OCAML_VERSION_PATCHLEVEL", .value = b.fmt("{d}", .{v.patchlevel}) },
        .{ .name = "OCAML_RELEASE_EXTRA", .value = release_extra },
    });

    const meta_content = src_info.renderAtTemplate("stdlib/META.in", &.{
        .{ .name = "configure_input", .value = "Generated by zcaml from stdlib/META.in", .version_specific = true },
        .{ .name = "VERSION", .value = v.version_string },
    });

    const config_wf = b.addWriteFiles();
    const sys_ml_lp = config_wf.add("sys.ml", sys_ml_content);
    const meta_lp = config_wf.add("META", meta_content);

    // 2. Determine launcher header format and compile tmpheader.exe if needed
    const header_format: HeaderFormat = if (v.sem_ver.order(.{ .major = 5, .minor = 5, .patch = 0 }) != .lt)
        .launch_info_5_5
    else if (v.sem_ver.order(.{ .major = 5, .minor = 2, .patch = 0 }) != .lt)
        .launch_info_5_2
    else
        .camlheader_5_0;

    const needs_header_exe = (header_format != .camlheader_5_0) or cfg.is_windows;
    const tmpheader_exe: ?*std.Build.Step.Compile = if (needs_header_exe)
        try buildTmpHeaderExe(b, ocaml_dep, options, header_format)
    else
        null;

    // 3. Generate alias-expanded sources and bytecode launcher headers
    var gen_src_cmd = Tools.Command{
        .gen_stdlib_sources = .{
            .ocaml_src_dir = .of(ocaml_dep.path("")),
            .header_exe = if (tmpheader_exe) |exe| .of(exe.getEmittedBin()) else null,
            .header_format = header_format,
            .is_windows_target = cfg.is_windows,
            .target_bindir = options.target_bindir,
            .expanded_dir = .of("stdlib_expanded"),
            .launcher_dir = .of("stdlib_launcher"),
        },
    };
    _ = gen_src_cmd.run(b);
    const expanded_dir = gen_src_cmd.gen_stdlib_sources.expanded_dir.lazyPath();
    const launcher_dir = gen_src_cmd.gen_stdlib_sources.launcher_dir.lazyPath();

    // 4. Build lookup table of StdlibUnit by module_name
    var unit_by_mod: std.StringHashMapUnmanaged(StdlibUnit) = .empty;
    for (m.stdlib_units) |u| {
        try unit_by_mod.put(b.allocator, u.module_name, u);
    }

    const boot_ocamlc = ocaml_dep.path("boot/ocamlc");
    const primitives = options.target_rt.primitives;

    const all_cmis_wf = b.addWriteFiles();
    const stdlib_out_wf = b.addWriteFiles();
    var prev_wave_dirs: std.ArrayList(std.Build.LazyPath) = .empty;
    var cmi_map: std.StringHashMapUnmanaged(std.Build.LazyPath) = .empty;
    var cmo_map: std.StringHashMapUnmanaged(std.Build.LazyPath) = .empty;

    // 5. Schedule .cmi waves via native Zig `b.addRunArtifact` steps
    for (m.stdlib_cmi_waves) |wave| {
        const wave_wf = b.addWriteFiles();
        for (wave) |mod_name| {
            const is_std_exit = std.mem.eql(u8, mod_name, "std_exit");
            const has_mli = if (is_std_exit) m.has_std_exit_mli else unit_by_mod.get(mod_name).?.has_mli;
            const unit_flags = if (is_std_exit) m.std_exit_compflags else unit_by_mod.get(mod_name).?.cmi_flags;

            const run = b.addRunArtifact(options.build_ocamlrun);
            run.addFileArg(boot_ocamlc);
            run.addArgs(&.{ "-nostdlib", "-use-prims" });
            run.addFileArg(primitives);
            run.addArgs(m.stdlib_compflags);
            run.addArgs(unit_flags);
            for (prev_wave_dirs.items) |wdir| {
                run.addArg("-I");
                run.addDirectoryArg(wdir);
            }

            const cmi_name = b.fmt("{s}.cmi", .{mod_name});
            if (!has_mli) {
                const u = unit_by_mod.get(mod_name).?;
                const ml_lp = resolveStdlibMlSource(b, ocaml_dep, expanded_dir, sys_ml_lp, u);
                const cmo_name = b.fmt("{s}.cmo", .{mod_name});
                const cmt_name = b.fmt("{s}.cmt", .{mod_name});

                run.addArgs(&.{ "-w", "-70", "-o" });
                const cmo_lp = run.addOutputFileArg(cmo_name);
                run.addArg("-c");
                run.addFileArg(ml_lp);

                const cmi_lp = cmo_lp.dirname().path(b, cmi_name);
                const cmt_lp = cmo_lp.dirname().path(b, cmt_name);
                _ = wave_wf.addCopyFile(cmi_lp, cmi_name);
                _ = all_cmis_wf.addCopyFile(cmi_lp, cmi_name);
                _ = stdlib_out_wf.addCopyFile(cmi_lp, cmi_name);
                _ = stdlib_out_wf.addCopyFile(cmt_lp, cmt_name);
                try cmi_map.put(b.allocator, mod_name, cmi_lp);
                try cmo_map.put(b.allocator, mod_name, cmo_lp);
            } else {
                const mli_lp = if (is_std_exit)
                    ocaml_dep.path("stdlib/std_exit.mli")
                else
                    resolveStdlibMliSource(b, ocaml_dep, expanded_dir, unit_by_mod.get(mod_name).?);
                const cmti_name = b.fmt("{s}.cmti", .{mod_name});

                run.addArg("-o");
                const cmi_lp = run.addOutputFileArg(cmi_name);
                run.addArg("-c");
                run.addFileArg(mli_lp);

                const cmti_lp = cmi_lp.dirname().path(b, cmti_name);
                _ = wave_wf.addCopyFile(cmi_lp, cmi_name);
                _ = all_cmis_wf.addCopyFile(cmi_lp, cmi_name);
                _ = stdlib_out_wf.addCopyFile(cmi_lp, cmi_name);
                _ = stdlib_out_wf.addCopyFile(cmti_lp, cmti_name);
                try cmi_map.put(b.allocator, mod_name, cmi_lp);
            }
        }
        try prev_wave_dirs.append(b.allocator, wave_wf.getDirectory());
    }

    const all_cmis_dir = all_cmis_wf.getDirectory();

    // 6. Schedule all .cmo compilations in unconstrained parallel via `b.addRunArtifact`
    for (m.stdlib_units) |u| {
        const ml_name = b.fmt("{s}.ml", .{u.basename});
        if (std.mem.eql(u8, u.basename, "sys")) {
            _ = stdlib_out_wf.addCopyFile(sys_ml_lp, "sys.ml");
        } else {
            _ = stdlib_out_wf.addCopyFile(ocaml_dep.path(b.fmt("stdlib/{s}", .{ml_name})), ml_name);
        }
        if (u.has_mli) {
            const mli_name = b.fmt("{s}.mli", .{u.basename});
            _ = stdlib_out_wf.addCopyFile(ocaml_dep.path(b.fmt("stdlib/{s}", .{mli_name})), mli_name);
        }

        if (cmo_map.contains(u.module_name)) continue;

        const run = b.addRunArtifact(options.build_ocamlrun);
        run.addFileArg(boot_ocamlc);
        run.addArgs(&.{ "-nostdlib", "-use-prims" });
        run.addFileArg(primitives);
        run.addArg("-I");
        run.addDirectoryArg(all_cmis_dir);
        run.addArgs(m.stdlib_compflags);
        run.addArgs(u.cmo_flags);
        run.addArg("-cmi-file");
        run.addFileArg(cmi_map.get(u.module_name).?);
        run.addArg("-o");

        const cmo_name = b.fmt("{s}.cmo", .{u.module_name});
        const cmt_name = b.fmt("{s}.cmt", .{u.module_name});
        const cmo_lp = run.addOutputFileArg(cmo_name);
        run.addArg("-c");
        run.addFileArg(resolveStdlibMlSource(b, ocaml_dep, expanded_dir, sys_ml_lp, u));

        const cmt_lp = cmo_lp.dirname().path(b, cmt_name);
        _ = stdlib_out_wf.addCopyFile(cmt_lp, cmt_name);
        try cmo_map.put(b.allocator, u.module_name, cmo_lp);
    }

    // 7. Compile std_exit.cmo
    {
        _ = stdlib_out_wf.addCopyFile(ocaml_dep.path("stdlib/std_exit.ml"), "std_exit.ml");
        if (m.has_std_exit_mli) {
            _ = stdlib_out_wf.addCopyFile(ocaml_dep.path("stdlib/std_exit.mli"), "std_exit.mli");
        }

        const run = b.addRunArtifact(options.build_ocamlrun);
        run.addFileArg(boot_ocamlc);
        run.addArgs(&.{ "-nostdlib", "-use-prims" });
        run.addFileArg(primitives);
        run.addArg("-I");
        run.addDirectoryArg(all_cmis_dir);
        run.addArgs(m.stdlib_compflags);
        run.addArgs(m.std_exit_compflags);
        if (cmi_map.get("std_exit")) |std_exit_cmi| {
            run.addArg("-cmi-file");
            run.addFileArg(std_exit_cmi);
        }
        run.addArg("-o");
        const std_exit_cmo = run.addOutputFileArg("std_exit.cmo");
        run.addArg("-c");
        run.addFileArg(ocaml_dep.path("stdlib/std_exit.ml"));

        _ = stdlib_out_wf.addCopyFile(std_exit_cmo, "std_exit.cmo");
        _ = stdlib_out_wf.addCopyFile(std_exit_cmo.dirname().path(b, "std_exit.cmt"), "std_exit.cmt");
        if (!m.has_std_exit_mli) {
            _ = stdlib_out_wf.addCopyFile(std_exit_cmo.dirname().path(b, "std_exit.cmi"), "std_exit.cmi");
        }
    }

    // 8. Link stdlib.cma
    {
        const link_run = b.addRunArtifact(options.build_ocamlrun);
        link_run.addFileArg(boot_ocamlc);
        link_run.addArgs(&.{ "-nostdlib", "-use-prims" });
        link_run.addFileArg(primitives);
        link_run.addArgs(&.{ "-a", "-o" });
        const stdlib_cma = link_run.addOutputFileArg("stdlib.cma");
        for (m.stdlib_units) |u| {
            link_run.addFileArg(cmo_map.get(u.module_name).?);
        }
        _ = stdlib_out_wf.addCopyFile(stdlib_cma, "stdlib.cma");
    }

    // 9. Copy bytecode launcher headers into stdlib_out_wf
    switch (header_format) {
        .launch_info_5_5, .launch_info_5_2 => {
            _ = stdlib_out_wf.addCopyFile(launcher_dir.path(b, "runtime-launch-info"), "runtime-launch-info");
        },
        .camlheader_5_0 => {
            for (&[_][]const u8{ "camlheader", "camlheaderd", "camlheaderi", "camlheader_ur" }) |hname| {
                _ = stdlib_out_wf.addCopyFile(launcher_dir.path(b, hname), hname);
            }
        },
    }

    return .{
        .stdlib_dir = stdlib_out_wf.getDirectory(),
        .meta_file = meta_lp,
        .unix_labels_mli = expanded_dir.path(b, "unixLabels.mli"),
        .header_format = header_format,
    };
}

fn resolveStdlibMliSource(
    b: *std.Build,
    ocaml_dep: *std.Build.Dependency,
    expanded_dir: std.Build.LazyPath,
    u: StdlibUnit,
) std.Build.LazyPath {
    const mli_name = b.fmt("{s}.mli", .{u.basename});
    if (u.expand_mli_aliases) {
        return expanded_dir.path(b, mli_name);
    }
    return ocaml_dep.path(b.fmt("stdlib/{s}", .{mli_name}));
}

fn resolveStdlibMlSource(
    b: *std.Build,
    ocaml_dep: *std.Build.Dependency,
    expanded_dir: std.Build.LazyPath,
    sys_ml_lp: std.Build.LazyPath,
    u: StdlibUnit,
) std.Build.LazyPath {
    if (std.mem.eql(u8, u.basename, "sys")) return sys_ml_lp;
    const ml_name = b.fmt("{s}.ml", .{u.basename});
    if (u.expand_ml_aliases) {
        return expanded_dir.path(b, ml_name);
    }
    return ocaml_dep.path(b.fmt("stdlib/{s}", .{ml_name}));
}

fn buildTmpHeaderExe(
    b: *std.Build,
    ocaml_dep: *std.Build.Dependency,
    options: BuildStdlibOptions,
    header_format: HeaderFormat,
) !*std.Build.Step.Compile {
    const cfg = options.target_cfg;
    const headers_dir = options.target_rt.headers_dir;
    const headers_caml_dir = headers_dir.path(b, "caml");

    const c_src_rel = switch (header_format) {
        .launch_info_5_5 => "stdlib/header.c",
        .launch_info_5_2, .camlheader_5_0 => if (cfg.is_windows) "stdlib/headernt.c" else "stdlib/header.c",
    };

    const tmpheader = b.addExecutable(.{
        .name = "tmpheader",
        .root_module = b.createModule(.{
            .target = cfg.resolved,
            .optimize = .ReleaseSmall,
            .strip = true,
            .link_libc = true,
        }),
    });
    tmpheader.root_module.addIncludePath(headers_dir);
    tmpheader.root_module.addIncludePath(headers_caml_dir);
    tmpheader.root_module.addIncludePath(ocaml_dep.path("runtime"));

    var cflags: std.ArrayList([]const u8) = .empty;
    try cflags.appendSlice(b.allocator, &.{
        "-O2",
        "-fno-strict-aliasing",
        "-fwrapv",
    });
    if (cfg.is_windows) {
        try cflags.appendSlice(b.allocator, &.{
            "-DUNICODE",
            "-D_UNICODE",
            "-DWINDOWS_UNICODE=1",
        });
        if (header_format == .launch_info_5_5) {
            try cflags.append(b.allocator, "-DwmainCRTStartup=wmain");
        }
        tmpheader.mingw_unicode_entry_point = true;
        tmpheader.subsystem = .Console;
    }

    tmpheader.root_module.addCSourceFile(.{
        .file = ocaml_dep.path(c_src_rel),
        .flags = cflags.items,
    });

    return tmpheader;
}
