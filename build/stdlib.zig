//! The standard library (`stdlib.cma` + interfaces), compiled with `boot/ocamlc`.
const std = @import("std");
const Source = @import("source.zig");
const Platform = @import("platform.zig");
const Ocamlc = @import("ocamlc.zig");
const runtime = @import("runtime.zig");
const Tools = @import("tools/root.zig");

pub const Artifacts = struct {
    /// Contents of `lib/ocaml/` contributed by the stdlib (flat, as upstream installs it).
    dir: std.Build.LazyPath,
    meta: std.Build.LazyPath,
    /// Module-alias-expanded sources (`Manifest.Src.expanded`), also used by otherlibs.
    expanded_dir: std.Build.LazyPath,
};

pub const Options = struct {
    target_rt: runtime.Artifacts,
    /// `ocamlrun` for the build machine, running `boot/ocamlc`.
    build_ocamlrun: *std.Build.Step.Compile,
};

pub fn build(src: *const Source, options: Options) Artifacts {
    const b = src.b;
    const m = src.manifest;
    const v = m.version;
    const p = options.target_rt.platform;

    // 1. stdlib/sys.ml and stdlib/META
    const release_extra = if (v.extra.len == 0)
        "None"
    else
        b.fmt("Some ({s}, \"{s}\")", .{ if (std.mem.eql(u8, v.extra_prefix, "~")) "Tilde" else "Plus", v.extra });

    const config = b.addWriteFiles();
    const sys_ml = config.add("sys.ml", src.renderAt("stdlib/sys.ml.in", &.{
        .{ .name = "configure_input", .value = "Generated by zcaml from stdlib/sys.ml.in" },
        .{ .name = "VERSION", .value = v.string },
        .{ .name = "OCAML_DEVELOPMENT_VERSION", .value = if (v.dev) "true" else "false" },
        .{ .name = "OCAML_VERSION_MAJOR", .value = b.fmt("{d}", .{v.major}) },
        .{ .name = "OCAML_VERSION_MINOR", .value = b.fmt("{d}", .{v.minor}) },
        .{ .name = "OCAML_VERSION_PATCHLEVEL", .value = b.fmt("{d}", .{v.patchlevel}) },
        .{ .name = "OCAML_RELEASE_EXTRA", .value = release_extra },
    }));
    const meta = config.add("META", src.renderMeta("stdlib/META.in", &.{}));

    // 2. Alias-expanded sources and bytecode launcher headers
    const header_format = m.features.header_format;
    const header_exe: ?*std.Build.Step.Compile = if (header_format != .camlheader or p.is_windows)
        buildHeaderExe(src.*, options.target_rt, header_format)
    else
        null;

    const gen, _ = Tools.run(b, .gen_stdlib_sources, .{
        .ocaml_src_dir = .of(src.path("")),
        .header_exe = if (header_exe) |exe| .of(exe.getEmittedBin()) else null,
        .header_format = header_format,
        .is_windows_target = p.is_windows,
        .expanded_dir = .of("stdlib_expanded"),
        .launcher_dir = .of("stdlib_launcher"),
    });
    const expanded_dir = gen.expanded_dir.lazyPath();
    const launcher_dir = gen.launcher_dir.lazyPath();

    var sources: Source.Resolver = .{ .source = src, .arch = p.arch, .expanded_dir = expanded_dir };
    sources.gen.put(.stdlib_sys_ml, sys_ml);

    // 3. Compile
    const boot: Ocamlc = .{
        .b = b,
        .ocamlrun = options.build_ocamlrun,
        .exe = src.path("boot/ocamlc"),
        .stdlib_dir = null,
        .primitives = options.target_rt.primitives,
    };
    const compiled = boot.compilePlan(m.stdlib.plan, sources, .{ .flags = m.stdlib.compflags });

    const out = b.addWriteFiles();
    for (compiled.intfs.values()) |u| {
        _ = out.addCopyFile(u.cmi, b.fmt("{s}.cmi", .{u.unit.name}));
        if (u.cmti) |cmti| {
            _ = out.addCopyFile(cmti, b.fmt("{s}.cmti", .{u.unit.name}));
            installSource(out, sources, u.unit.src);
        }
    }
    for (compiled.impls.values()) |u| {
        _ = out.addCopyFile(u.impl.cmt, b.fmt("{s}.cmt", .{u.unit.name}));
        installSource(out, sources, u.unit.src);
    }
    _ = out.addCopyFile(compiled.cmo("std_exit").?, "std_exit.cmo");

    // 4. stdlib.cma
    _ = out.addCopyFile(boot.archive("stdlib.cma", compiled.cmos(b, m.stdlib.cma), .{}), "stdlib.cma");

    // 5. Launcher headers
    switch (header_format) {
        .launch_info_5_5, .launch_info_5_2 => {
            _ = out.addCopyFile(launcher_dir.path(b, "runtime-launch-info"), "runtime-launch-info");
        },
        .camlheader => for ([_][]const u8{ "camlheader", "camlheaderd", "camlheaderi", "camlheader_ur" }) |name| {
            _ = out.addCopyFile(launcher_dir.path(b, name), name);
        },
    }

    return .{
        .dir = out.getDirectory(),
        .meta = meta,
        .expanded_dir = expanded_dir,
    };
}

/// Install the pristine source of a unit next to its artifacts (`stdlib/foo.ml` -> `foo.ml`).
fn installSource(out: *std.Build.Step.WriteFile, sources: Source.Resolver, src: Source.Manifest.Src) void {
    const name = switch (src) {
        .upstream, .expanded => |rel| std.fs.path.basename(rel),
        .gen => |g| switch (g) {
            .stdlib_sys_ml => "sys.ml",
            else => std.debug.panic("unexpected generated stdlib source '{t}'", .{g}),
        },
        .arch => unreachable,
    };
    _ = out.addCopyFile(sources.original(src), name);
}

/// The executable embedded into bytecode programs that launches `ocamlrun`.
fn buildHeaderExe(src: Source, target_rt: runtime.Artifacts, header_format: Source.Manifest.HeaderFormat) *std.Build.Step.Compile {
    const b = src.b;
    const p = target_rt.platform;

    const exe = b.addExecutable(.{
        .name = "tmpheader",
        .root_module = runtime.cModule(b, p, .ReleaseSmall, .{ .strip = true }),
    });
    target_rt.addIncludes(src, exe.root_module);

    var extra: []const []const u8 = &.{};
    if (p.is_windows) {
        if (header_format == .launch_info_5_5) extra = &.{"-DwmainCRTStartup=wmain"};
        exe.mingw_unicode_entry_point = true;
        exe.subsystem = .console;
    }
    exe.root_module.addCSourceFile(.{
        .file = src.path(if (p.is_windows and header_format != .launch_info_5_5) "stdlib/headernt.c" else "stdlib/header.c"),
        .flags = p.c.flags(b, extra),
    });
    return exe;
}
