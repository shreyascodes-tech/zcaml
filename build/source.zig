//! An OCaml source tree (a `build.zig.zon` dependency) together with its manifest.
const std = @import("std");
const templates = @import("templates.zig");
const Versions = @import("versions.zig");
pub const Manifest = @import("manifests/manifest.zig");

pub const Var = templates.Var;

const Source = @This();

b: *std.Build,
dep: *std.Build.Dependency,
manifest: Manifest,

pub fn load(b: *std.Build, dep: *std.Build.Dependency, version: Versions.Version) Source {
    const manifest_path = Versions.manifestPath(version);
    const zon_src_file = b.root.openFile(b.graph.io, manifest_path, .{ .mode = .read_only }) catch |err| std.debug.panic(
        "Failed to open manifest '{s}' for OCaml {t} ({t}). Run `zig build generate`.",
        .{ manifest_path, version, err },
    );
    defer zon_src_file.close(b.graph.io);

    var zon_src_read_buf: [2048]u8 = undefined;
    var zon_src_reader = zon_src_file.reader(b.graph.io, &zon_src_read_buf);
    const zon_src = zon_src_reader.interface.allocRemainingAlignedSentinel(b.allocator, .unlimited, .of(u8), 0) catch |err| std.debug.panic(
        "Failed to read manifest '{s}' for OCaml {t} ({t}). Run `zig build generate`.",
        .{ manifest_path, version, err },
    );

    @setEvalBranchQuota(20_000);
    var diag: std.zon.parse.Diagnostics = undefined;
    const manifest = std.zon.parse.fromSlice(Manifest, .{
        .gpa = b.allocator,
        .arena = b.graph.arena,
        .diagnostics = &diag,
        .source = zon_src,
        .ignore_unknown_fields = true,
    }) catch |err| {
        std.debug.panic("Failed to parse manifest '{s}': {t}\n{f}\nRun `zig build generate`.", .{ manifest_path, err, diag.fmt(manifest_path) });
    };

    if (!std.mem.eql(u8, manifest.version.string, @tagName(version))) std.debug.panic(
        "Manifest '{s}' is for OCaml {s}, expected {t}. Run `zig build generate`.",
        .{ manifest_path, manifest.version.string, version },
    );

    return .{ .b = b, .dep = dep, .manifest = manifest };
}

pub fn path(self: Source, sub_path: []const u8) std.Build.LazyPath {
    return self.dep.path(sub_path);
}

/// Read a file from the source tree at configure time.
pub fn read(self: Source, sub_path: []const u8) []const u8 {
    const file = self.dep.builder.root.openFile(self.b.graph.io, sub_path, .{ .mode = .read_only }) catch |err| std.debug.panic(
        "Failed to read '{s}' from OCaml source dependency: {t}",
        .{ sub_path, err },
    );
    defer file.close(self.b.graph.io);
    var buf: [2048]u8 = undefined;
    var reader = file.reader(self.b.graph.io, &buf);
    return reader.interface.allocRemainingAlignedSentinel(self.b.allocator, .unlimited, .of(u8), 0) catch |err| std.debug.panic(
        "Failed to read '{s}' from OCaml source dependency: {t}",
        .{ sub_path, err },
    );
}

/// Render a `@var@` template from the source tree.
pub fn renderAt(self: Source, template: []const u8, vars: []const Var) []const u8 {
    return templates.renderText(self.b.allocator, template, self.read(template), vars);
}

/// Render an autoconf `#undef` C header template from the source tree.
pub fn renderConfigHeader(
    self: Source,
    template: []const u8,
    vars: []const Var,
    keep_defines: []const []const u8,
    footer: []const u8,
) []const u8 {
    return templates.renderConfigHeader(self.b.allocator, template, self.read(template), vars, keep_defines, footer);
}

/// Render a library `META.in` (only `@VERSION@` + extras).
pub fn renderMeta(self: Source, template: []const u8, extra: []const Var) []const u8 {
    var vars: std.ArrayList(Var) = .empty;
    vars.appendSlice(self.b.allocator, &.{
        .{ .name = "configure_input", .value = self.b.fmt("Generated by zcaml from {s}", .{template}), .version_specific = true },
        .{ .name = "VERSION", .value = self.manifest.version.string },
    }) catch @panic("OOM");
    vars.appendSlice(self.b.allocator, extra) catch @panic("OOM");
    return self.renderAt(template, vars.items);
}

/// Resolves `Manifest.Src` to build paths for one target architecture.
pub const Resolver = struct {
    source: *const Source,
    arch: ?Manifest.Arch,
    /// Output of `gen_stdlib_sources` (mirrors upstream relative paths).
    expanded_dir: ?std.Build.LazyPath = null,
    gen: std.EnumMap(Manifest.Gen, std.Build.LazyPath) = .{},

    pub fn resolve(self: Resolver, src: Manifest.Src) std.Build.LazyPath {
        const b = self.source.b;
        return switch (src) {
            .upstream => |p| self.source.path(p),
            .arch => |name| self.source.path(b.fmt("asmcomp/{s}/{s}", .{
                if (self.arch) |a| @tagName(a) else std.debug.panic("'{s}' needs a native backend", .{name}),
                name,
            })),
            .expanded => |p| (self.expanded_dir orelse std.debug.panic("expanded source '{s}' not available here", .{p})).path(b, p),
            .gen => |g| self.gen.get(g) orelse std.debug.panic("generated source '{t}' not available here", .{g}),
        };
    }

    /// The pristine upstream file behind `src`, for installing sources next to
    /// their compiled artifacts.
    pub fn original(self: Resolver, src: Manifest.Src) std.Build.LazyPath {
        return switch (src) {
            .expanded => |p| self.source.path(p),
            else => self.resolve(src),
        };
    }
};
