//! Builds the OCaml C runtime for a given target State.
//!
//! Mirrors upstream's runtime rules (see the `runtime/` section of the root
//! Makefile): `libcamlrun.a` is built from the bytecode C sources, then
//! `ocamlrun` is linked from `prims.o` + `libcamlrun.a`.

const std = @import("std");
const State = @import("state.zig");
const tools = @import("tools.zig");
const version_h = @import("config/version_h.zig");
const exec_h = @import("config/exec_h.zig");
const m_h = @import("config/m_h.zig");
const s_h = @import("config/s_h.zig");
const Config = @import("config/static.zig");
const TargetConfig = @import("config/target.zig");

const LazyPath = std.Build.LazyPath;

pub const Bytecode = struct {
    state: *State,
    /// `libcamlrun.a`: the bytecode runtime without `prims.c`.
    lib: *std.Build.Step.Compile,
    /// The `ocamlrun` bytecode interpreter.
    exe: *std.Build.Step.Compile,
    /// Directory containing `caml/*.h` generated for this target.
    generated_headers: LazyPath,

    /// Runs `ocamlrun` at build time.  Only valid for the host State.
    pub fn cmd(self: *const Bytecode) *tools.Cmd {
        std.debug.assert(self.state.isHost());
        return tools.Cmd.init(self.state.ctx.b, self.exe);
    }
};

/// Builds the bytecode runtime (`libcamlrun` + `ocamlrun`) for `state`.
/// Use `State.bytecodeRuntime`, which caches the result.
pub fn bytecode(state: *State) Bytecode {
    const ctx = state.ctx;
    const b = ctx.b;
    State.requireLinuxTarget("runtime.zig", state.result());

    const headers = generatedHeaders(state);

    const lib_mod = b.createModule(.{
        .target = state.target,
        .optimize = state.optimize,
        .link_libc = true,
        .pic = true,
    });
    addIncludes(state, lib_mod, headers);
    lib_mod.addCSourceFiles(.{
        .language = .c,
        .root = ctx.ocamlRel("runtime"),
        .files = &bytecode_sources,
        .flags = &(common_c_flags ++ runtime_cpp_flags),
    });
    lib_mod.linkLibrary(state.zstd);
    const lib = b.addLibrary(.{
        .name = "camlrun",
        .linkage = .static,
        .root_module = lib_mod,
    });

    const prims_c = ctx.tool("tools/gen-prims.zig").cmd(b).outFile("prims.c");
    for (bytecode_sources) |source_name| {
        _ = prims_c.inFile(ctx.ocamlRel(b.fmt("runtime/{s}", .{source_name})));
    }

    const exe_mod = b.createModule(.{
        .target = state.target,
        .optimize = state.optimize,
        .link_libc = true,
        .pic = true,
    });
    addIncludes(state, exe_mod, headers);
    // Upstream compiles prims.c without the runtime-only cpp flags.
    exe_mod.addCSourceFile(.{
        .file = prims_c.popOutFile(),
        .language = .c,
        .flags = &common_c_flags,
    });
    exe_mod.linkLibrary(lib);
    exe_mod.linkLibrary(state.zstd);
    exe_mod.linkSystemLibrary("m", .{});
    exe_mod.linkSystemLibrary("pthread", .{});

    const exe = b.addExecutable(.{
        .name = "ocamlrun",
        .root_module = exe_mod,
    });
    // Upstream links ocamlrun with `-Wl,-E` on ELF so that dynamically
    // loaded C stubs (dllfoo.so) can resolve runtime symbols.
    exe.rdynamic = true;

    return .{
        .state = state,
        .lib = lib,
        .exe = exe,
        .generated_headers = headers,
    };
}

fn addIncludes(state: *State, mod: *std.Build.Module, headers: LazyPath) void {
    const b = state.ctx.b;
    // Upstream generates m.h/s.h/exec.h next to runtime/caml/*.h, and those
    // headers include them as `#include "m.h"`.  We can't write into the
    // package dir, so expose the generated `caml/` dir as an include root too.
    mod.addIncludePath(headers);
    mod.addIncludePath(headers.path(b, "caml"));
    mod.addIncludePath(state.ctx.ocamlRel("runtime"));
    mod.addIncludePath(state.zstd.getEmittedIncludeTree());
}

/// Generates the configure/make-produced runtime headers for `state`'s target.
/// Layout matches upstream: everything under `caml/`, plus `build_config.h`
/// at the root (it lives in `runtime/` upstream).
fn generatedHeaders(state: *State) LazyPath {
    const ctx = state.ctx;
    const b = ctx.b;
    const target = state.result();
    const wf = b.addWriteFiles();
    _ = wf.addCopyFile(version_h.generate(ctx), "caml/version.h");
    _ = wf.addCopyFile(exec_h.generate(ctx), "caml/exec.h");
    _ = wf.addCopyFile(m_h.generate(state), "caml/m.h");
    _ = wf.addCopyFile(s_h.generate(state), "caml/s.h");

    const jumptbl = ctx.tool("tools/gen-jumptbl.zig").cmd(b)
        .outFile("jumptbl.h")
        .inFile(ctx.ocamlRel("runtime/caml/instruct.h"))
        .popOutFile();
    _ = wf.addCopyFile(jumptbl, "caml/jumptbl.h");

    const triple = TargetConfig.ocamlTriple(b.allocator, target.*);
    _ = wf.add("build_config.h", b.fmt(
        \\/* Generated by zcaml */
        \\#define OCAML_STDLIB_DIR "{f}"
        \\#define HOST "{f}"
        \\#define BYTECODE_RUNTIME_ID "{f}"
        \\
    , .{
        std.zig.fmtString(Config.stdlib_dir),
        std.zig.fmtString(triple),
        std.zig.fmtString(Config.bytecodeRuntimeId(target.*)),
    }));

    return wf.getDirectory();
}

