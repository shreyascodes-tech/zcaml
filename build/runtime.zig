/// `OC_CFLAGS` + `OC_CPPFLAGS` from configure for clang on Unix.
/// Optimization level comes from the State's optimize mode.
const common_c_flags = [_][]const u8{
    "-std=gnu11",
    "-fno-strict-aliasing",
    "-fwrapv",
    "-fno-common",
    "-D_FILE_OFFSET_BITS=64",
};

/// `runtime_CPPFLAGS` from the upstream Makefile: applied to runtime objects
/// but not to prims.c.
const runtime_cpp_flags = [_][]const u8{
    "-DCAMLDLLIMPORT=",
    "-DIN_CAML_RUNTIME",
};
