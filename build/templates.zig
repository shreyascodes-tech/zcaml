//! Strict renderers for the autoconf-style templates in the OCaml source tree.
//!
//! "Strict" means rendering panics if the template references a variable that is
//! not in the substitution table, or if the table contains an entry the template
//! does not use (unless it is marked `version_specific`). This catches upstream
//! drift instead of silently producing a broken configuration.
const std = @import("std");

pub const Var = struct {
    name: []const u8,
    /// `null` renders `#undef` for C headers (not allowed for text templates).
    value: ?[]const u8,
    /// Only exists in some OCaml releases; don't fail if the template lacks it.
    version_specific: bool = false,
};

/// Render a text template with `@var@` placeholders.
pub fn renderText(
    gpa: std.mem.Allocator,
    template_name: []const u8,
    template: []const u8,
    vars: []const Var,
) []const u8 {
    checkDuplicates(template_name, vars);
    const used = gpa.alloc(bool, vars.len) catch @panic("OOM");
    @memset(used, false);

    var out: std.ArrayList(u8) = .empty;
    var i: usize = 0;
    while (i < template.len) {
        if (template[i] == '@') {
            const name_start = i + 1;
            const name_end = identEnd(template, name_start);
            if (name_end > name_start and name_end < template.len and template[name_end] == '@') {
                const name = template[name_start..name_end];
                const idx = findVar(vars, name) orelse std.debug.panic(
                    "Template safety check failed in '{s}': placeholder '@{s}@' is not handled in zcaml substitution table",
                    .{ template_name, name },
                );
                used[idx] = true;
                const value = vars[idx].value orelse std.debug.panic(
                    "'{s}' in '{s}' has no value",
                    .{ name, template_name },
                );
                out.appendSlice(gpa, value) catch @panic("OOM");
                i = name_end + 1;
                continue;
            }
        }
        out.append(gpa, template[i]) catch @panic("OOM");
        i += 1;
    }

    checkUnused(template_name, vars, used);
    return out.items;
}

/// Render an autoconf C header template (`#undef NAME` lines, e.g. `runtime/caml/s.h.in`).
/// `#define`s already present in the template must either be in `vars` (and get
/// replaced) or be listed in `keep_defines`.
pub fn renderConfigHeader(
    gpa: std.mem.Allocator,
    template_name: []const u8,
    template: []const u8,
    vars: []const Var,
    keep_defines: []const []const u8,
    footer: []const u8,
) []const u8 {
    checkDuplicates(template_name, vars);
    const used = gpa.alloc(bool, vars.len) catch @panic("OOM");
    @memset(used, false);

    var out: std.ArrayList(u8) = .empty;
    out.print(gpa, "/* Generated by zcaml from {s} */\n", .{template_name}) catch @panic("OOM");

    var lines = std.mem.splitScalar(u8, template, '\n');
    while (lines.next()) |raw_line| {
        const line = std.mem.trimEnd(u8, raw_line, "\r");
        const trimmed = std.mem.trim(u8, line, " \t");

        const directive: ?[]const u8 = if (std.mem.startsWith(u8, trimmed, "#undef "))
            "#undef "
        else if (std.mem.startsWith(u8, trimmed, "#define "))
            "#define "
        else
            null;

        if (directive) |d| {
            const rest = std.mem.trimStart(u8, trimmed[d.len..], " \t");
            const name = rest[0..identEnd(rest, 0)];
            const is_define = d[1] == 'd';

            if (is_define and containsStr(keep_defines, name)) {
                out.print(gpa, "{s}\n", .{line}) catch @panic("OOM");
                continue;
            }

            const idx = findVar(vars, name) orelse if (is_define) std.debug.panic(
                "Template safety check failed in '{s}': unexpected '#define {s}' in template",
                .{ template_name, name },
            ) else std.debug.panic(
                "Template safety check failed in '{s}': macro '#undef {s}' is not handled in zcaml config table",
                .{ template_name, name },
            );
            used[idx] = true;
            if (vars[idx].value) |val| {
                out.print(gpa, "#define {s} {s}\n", .{ name, val }) catch @panic("OOM");
            } else {
                out.print(gpa, "/* #undef {s} */\n", .{name}) catch @panic("OOM");
            }
        } else {
            out.print(gpa, "{s}\n", .{line}) catch @panic("OOM");
        }
    }

    checkUnused(template_name, vars, used);
    out.appendSlice(gpa, footer) catch @panic("OOM");
    return out.items;
}

fn checkDuplicates(template_name: []const u8, vars: []const Var) void {
    for (vars, 0..) |a, i| {
        for (vars[i + 1 ..]) |b| {
            if (std.mem.eql(u8, a.name, b.name)) {
                std.debug.panic("Duplicate '{s}' in substitution table for '{s}'", .{ a.name, template_name });
            }
        }
    }
}

fn checkUnused(template_name: []const u8, vars: []const Var, used: []const bool) void {
    for (vars, used) |v, u| {
        if (!u and !v.version_specific) std.debug.panic(
            "Template safety check failed in '{s}': '{s}' in zcaml substitution table does not exist in template",
            .{ template_name, v.name },
        );
    }
}

fn identEnd(s: []const u8, start: usize) usize {
    if (start >= s.len or !(std.ascii.isAlphabetic(s[start]) or s[start] == '_')) return start;
    var i = start + 1;
    while (i < s.len and (std.ascii.isAlphanumeric(s[i]) or s[i] == '_')) : (i += 1) {}
    return i;
}

fn findVar(vars: []const Var, name: []const u8) ?usize {
    for (vars, 0..) |v, i| {
        if (std.mem.eql(u8, v.name, name)) return i;
    }
    return null;
}

fn containsStr(haystack: []const []const u8, needle: []const u8) bool {
    for (haystack) |s| {
        if (std.mem.eql(u8, s, needle)) return true;
    }
    return false;
}

test renderText {
    const gpa = std.testing.allocator;
    var arena: std.heap.ArenaAllocator = .init(gpa);
    defer arena.deinit();
    const out = renderText(arena.allocator(), "t", "a @x@ b @y z %%Q%%", &.{
        .{ .name = "x", .value = "1" },
        .{ .name = "v", .value = "2", .version_specific = true },
    });
    try std.testing.expectEqualStrings("a 1 b @y z %%Q%%", out);
}

test renderConfigHeader {
    const gpa = std.testing.allocator;
    var arena: std.heap.ArenaAllocator = .init(gpa);
    defer arena.deinit();
    const out = renderConfigHeader(arena.allocator(), "t.h.in", "#undef A\n#undef B\n#define K 1\n", &.{
        .{ .name = "A", .value = "1" },
        .{ .name = "B", .value = null },
    }, &.{"K"}, "");
    try std.testing.expectEqualStrings("/* Generated by zcaml from t.h.in */\n#define A 1\n/* #undef B */\n#define K 1\n\n", out);
}
