pub const runtime_ids = struct {
    // OCaml 5.5.1 with the vendored zstd compression library enabled: the low
    // runtime-id bits encode the 32/64-bit pointer configuration.
    pub const bytecode_32 = "a101";
    pub const bytecode_64 = "a100";
    pub const native_32 = bytecode_32;
    pub const native_64 = bytecode_64;
};

pub fn bytecodeRuntimeId(target: std.Target) []const u8 {
    return if (target.ptrBitWidth() == 64)
        runtime_ids.bytecode_64
    else
        runtime_ids.bytecode_32;
}
